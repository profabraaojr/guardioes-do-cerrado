  const TOP = 2;          // linhas reservadas para acentos de maiúsculas
  const CELL_H = TOP + 9; // altura total da célula
  const LINE_H = CELL_H + 2;
  const glyphs = {};      // char -> {w, px: [[x,y],...]}

  function build(rows) {
    const px = []; let w = 0;
    rows.forEach((r, y) => { w = Math.max(w, r.length); for (let x = 0; x < r.length; x++) if (r[x] === '#') px.push([x, y + TOP]); });
    return { w, px };
  }
  Object.keys(G).forEach((c) => (glyphs[c] = build(G[c])));
  Object.keys(COMPOSE).forEach((c) => {
    const [base, acc] = COMPOSE[c];
    const b = glyphs[base];
    const g = { w: b.w, px: b.px.slice() };
    const upper = base === base.toUpperCase() && base !== 'ı';
    if (acc === 'cedil') {
      const cx = Math.floor(b.w / 2);
      g.px.push([cx, 7 + TOP], [cx - 1, 8 + TOP]);
    } else {
      const a = ACC[acc];
      const aw = a[0].length;
      const ox = Math.max(0, Math.floor((b.w - aw) / 2));
      const oy = upper ? 0 : TOP;
      a.forEach((r, y) => { for (let x = 0; x < r.length; x++) if (r[x] === '#') g.px.push([ox + x, oy + y]); });
      g.w = Math.max(b.w, ox + aw);
    }
    glyphs[c] = g;
  });
  glyphs[' '] = { w: 3, px: [] };
  const fallback = glyphs['?'];

  function glyph(c) { return glyphs[c] || fallback; }
  function width(text) {
    let w = 0;
    for (const c of text) w += glyph(c).w + 1;
    return Math.max(0, w - 1);
  }
  // desenha em coordenadas de pixel de interface (escala 1)
  function draw(ctx, text, x, y, color, shadow) {
    let cx = Math.round(x); y = Math.round(y);
    for (const c of text) {
      const g = glyph(c);
      if (shadow) { ctx.fillStyle = shadow; for (const [px, py] of g.px) ctx.fillRect(cx + px, y + py + 1, 1, 1); }
      ctx.fillStyle = color;
      for (const [px, py] of g.px) ctx.fillRect(cx + px, y + py, 1, 1);
      cx += g.w + 1;
    }
    return cx;
  }
  // texto com trechos destacados: {a|texto} ciano, {y|texto} amarelo, {g|texto} verde
  function parse(text) {
    const runs = []; const re = /\{([ayg])\|([^}]*)\}/g; let last = 0, m;
    while ((m = re.exec(text))) {
      if (m.index > last) runs.push({ t: text.slice(last, m.index), c: null });
      runs.push({ t: m[2], c: m[1] });
      last = re.lastIndex;
    }
    if (last < text.length) runs.push({ t: text.slice(last), c: null });
    return runs;
  }
  function plain(text) { return parse(text).map((r) => r.t).join(''); }
  // quebra automática por palavras; devolve linhas como listas de trechos coloridos
  function wrap(text, maxW) {
    const words = [];
    for (const r of parse(text)) {
      r.t.split(/(\s+)/).forEach((p) => { if (p) words.push({ t: p, c: r.c, space: /^\s+$/.test(p) }); });
    }
    const lines = [[]]; let w = 0;
    for (const wd of words) {
      if (wd.t.includes('\n')) { lines.push([]); w = 0; continue; }
      const ww = width(wd.t) + 1;
      if (wd.space) { if (w > 0) { lines[lines.length - 1].push({ t: ' ', c: null }); w += 4; } continue; }
      if (w > 0 && w + ww > maxW) {
        const L = lines[lines.length - 1]; if (L.length && L[L.length - 1].t === ' ') L.pop();
        lines.push([]); w = 0;
      }
      // palavra maior que a linha: quebra por caractere
      if (ww > maxW) {
        let chunk = '';
        for (const ch of wd.t) { if (width(chunk + ch) > maxW) { lines[lines.length - 1].push({ t: chunk, c: wd.c }); lines.push([]); chunk = ''; } chunk += ch; }
        lines[lines.length - 1].push({ t: chunk, c: wd.c }); w = width(chunk) + 1; continue;
      }
      lines[lines.length - 1].push({ t: wd.t, c: wd.c }); w += ww;
    }
    return lines.filter((l, i) => l.length || i === 0);
  }
  return { draw, width, wrap, parse, plain, glyph, LINE_H, CELL_H, TOP, has: (c) => !!glyphs[c] };
